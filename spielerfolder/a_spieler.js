    const spielerGrid =
    document.querySelector(
        ".spieler-grid"
    );

    function renderHallOfFame() {

    const ranking =

        Object.values(players)

        .sort(
            (a, b) =>
            (b.trophies || 0) -
            (a.trophies || 0)
        )

        .slice(0, 4);

    hofGrid.innerHTML = "";

    ranking.forEach(
        (player, index) => {

            hofGrid.innerHTML += `

                <div class="hof-card ${index === 0 ? "gold" : ""}">

                    <span class="rank">
                        ${index + 1}
                    </span>

                    <img
                        src="${player.image}"
                        alt="${player.name}">

                    <h3>
                        ${player.name}
                    </h3>

                    <div class="hof-trophies">

                        ${'<img src="spielerfolder/trophy.png" class="hof-trophy-icon">'.repeat(player.trophies || 0)}

                    </div>

                </div>

            `;
        }
    );
}

function renderPlayerDetail(playerId) {

    const player =
        players[playerId];

    if(!player){
        return;
    }

    const winsCount =
    (player.wins || []).length;

    const winRate =
    player.eventsPlayed > 0
        ? (
            winsCount /
            player.eventsPlayed
        ) * 100
        : 0;

    playerDetail.innerHTML = `

        <div class="player-detail">

            <div class="player-left">

                <img
                    src="${player.image}"
                    alt="${player.name}">

                <div class="player-info">

                    <h2>${player.name}</h2>

                    <span>
                        ${player.role}
                    </span>

                    <div class="player-trophies">

                    ${'<img src="spielerfolder/trophy.png" class="trophy-icon">'.repeat(player.trophies)}

                    </div>

                    <p>
                        ${player.quote}
                    </p>

                </div>

            </div>

            <div class="player-facts">

                <div class="fact-box">
                    <h4>Lieblingskampagne</h4>
                    <p>${player.campaign}</p>
                </div>

                <div class="fact-box">
                    <h4>Lieblings-Survivor</h4>
                    <p>${player.survivor}</p>
                </div>

                <div class="fact-box">
                    <h4>Lieblingswaffe</h4>
                    <p>${player.weapon}</p>
                </div>

                <div class="fact-box">
                    <h4>Gefürchtetster Gegner</h4>
                    <p>${player.enemy}</p>
                </div>

                <div class="fact-box">
                    <h4>gespielte LANs</h4>
                    <p>${player.eventsPlayed}</p>
                </div>

                <div class="fact-box">
                    <h4>Winrate</h4>
                    <p>${winRate.toFixed(0)}%</p>
                </div>

                <div class="fact-box full">
                    <h4>Größter LAN-Moment</h4>
                    <p>${player.moment}</p>
                </div>
                
                <div class="fact-box full">
                    <h4>Gewonnene LANs</h4>

                    <div class="wins-slider">

                        ${
                            (player.wins || [])
                            .map(win => `

                                <a
                                    href="${win.link}"
                                    class="win-card">

                                    <img
                                        src="${win.image}"
                                        alt="${win.name}">

                                    <span>${win.name}</span>

                                </a>

                            `)
                            .join("")
                        }

                    </div>

                </div>

            </div>

        </div>

    `;
}

renderHallOfFame();

document
    .querySelectorAll(".spieler-card")
    .forEach(card => {

        card.addEventListener(
            "click",
            () => {

                const alreadyActive =
                    card.classList.contains(
                        "active"
                    );

                document
                    .querySelectorAll(
                        ".spieler-card"
                    )
                    .forEach(c =>
                        c.classList.remove(
                            "active"
                        )
                    );

                if(alreadyActive){

                    playerDetail.innerHTML = "";

                    return;
                }

                card.classList.add(
                    "active"
                );

                if(window.innerWidth <= 900){

    setTimeout(() => {

        playerDetail.scrollIntoView({

            behavior: "smooth",
            block: "start"

        });

    }, 100);

}

                renderPlayerDetail(
                    card.dataset.player
                );

            }
        );

    });
